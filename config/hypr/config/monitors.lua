-- Настройки подключённых мониторов.
--
-- ВАЖНО: это единственный файл, который почти наверняка придётся
-- поправить под конкретную машину — имена выходов (eDP-1, HDMI-A-1
-- и т.п.) и разрешения у каждого ноутбука/монитора свои.
-- Узнать актуальные имена и режимы: `hyprctl monitors` после первого
-- запуска Hyprland.

-- ---- Дефолт, который работает "из коробки" на любой машине ----
hl.monitor({
    output   = "eDP-1",
    mode     = "1920x1080@120",
    position = "0x0",
    scale    = "1.2",
})

